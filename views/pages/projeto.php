<section class="project-hero">
    <h1>Sobre o projeto</h1>
    <p>
        Este site foi desenvolvido para transformar o estudo dos tipos sanguíneos em uma experiência
        mais prática, visual e fácil de entender. A proposta une conhecimentos de Biologia, genética e
        desenvolvimento web em um único projeto educativo.
    </p>
</section>

<section class="card">
    <h2>Como surgiu a ideia?</h2>
    <p>
        Tipos como A+, O-, AB+ e B- são conhecidos por muita gente, mas nem sempre é fácil entender
        o que eles realmente significam. Perguntas como "por que um tipo pode receber de outro?",
        "como o sangue do bebê é herdado?" e "por que o fator Rh importa na gestação?" misturam
        conceitos de imunologia, genética e transfusão.
    </p>
    <p>
        A ideia do projeto foi reunir essas informações em um site que não apenas mostre um resultado,
        mas também explique <strong>por que o resultado acontece</strong>.
    </p>
</section>

<section class="card">
    <h2>Objetivo principal</h2>
    <p>
        Criar uma ferramenta web educativa que permita consultar compatibilidade básica de hemácias,
        explorar a herança dos tipos sanguíneos e entender, em linguagem simples, os mecanismos por trás
        desses resultados.
    </p>

    <div class="grid three">
        <div class="result-box">
            <h3>Informar</h3>
            <p>Explicar antígenos, anticorpos, ABO, RhD e genética sem depender apenas de tabelas.</p>
        </div>
        <div class="result-box">
            <h3>Calcular</h3>
            <p>Comparar dois tipos e apresentar compatibilidade e possibilidades genéticas de filhos.</p>
        </div>
        <div class="result-box">
            <h3>Ensinar</h3>
            <p>Mostrar curiosidades, casos raros, mitos, doação de sangue e cuidados relacionados à gestação.</p>
        </div>
    </div>
</section>

<section class="card">
    <h2>O que o site faz?</h2>
    <div class="genetics-flow">
        <div class="genetics-step"><strong>1. Cadastro</strong>O usuário informa nome, e-mail, senha e tipo sanguíneo.</div>
        <div class="genetics-step"><strong>2. Consulta</strong>O sistema compara dois tipos e mostra doação e recebimento de hemácias.</div>
        <div class="genetics-step"><strong>3. Herança</strong>O sistema calcula uma distribuição consolidada dos tipos possíveis do bebê.</div>
        <div class="genetics-step"><strong>4. Gestação</strong>A consulta considera ABO, RhD e limitações relacionadas a outros anticorpos.</div>
        <div class="genetics-step"><strong>5. Aprendizado</strong>A página Entenda explica os conceitos científicos por trás das regras.</div>
        <div class="genetics-step"><strong>6. Histórico</strong>As consultas do usuário ficam registradas para consulta posterior.</div>
    </div>
</section>

<section class="card">
    <h2>Como a programação entra no projeto?</h2>
    <p>
        O sistema transforma regras biológicas em lógica computacional. PHP processa os cálculos e a
        comunicação com o banco de dados MySQL, enquanto HTML, CSS e JavaScript cuidam da interface,
        navegação, responsividade e preferência de tema. Assim, o projeto conecta conteúdo científico com
        desenvolvimento de software.
    </p>
</section>

<section class="card">
    <h2>Limites do modelo</h2>
    <p>
        O site é uma ferramenta educativa e trabalha principalmente com os sistemas ABO e RhD. A medicina
        transfusional real considera muitos outros sistemas, antígenos, anticorpos, histórico do paciente e
        testes laboratoriais. A parte genética também usa um modelo simplificado de herança para transformar
        a incerteza dos genótipos em uma única tabela de probabilidades.
    </p>
    <div class="alert info-note">
        <strong>Em resumo:</strong> o objetivo não é substituir um hemocentro, laboratório ou profissional de saúde,
        e sim tornar o tema mais fácil de estudar, visualizar e discutir.
    </div>
</section>
