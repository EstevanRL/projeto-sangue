<section class="card">
    <h1>Entenda de verdade os tipos sanguíneos</h1>
    <p class="muted">
        Os nomes A+, O-, AB+ e outros parecem simples, mas eles representam algumas características
        do sangue que o sistema imunológico consegue reconhecer. Esta página explica o que muda entre
        os tipos, por que existe incompatibilidade, como o fator Rh funciona e por que a realidade é
        um pouco maior do que os oito tipos mostrados pelo site.
    </p>

    <div class="result-box info-note">
        <strong>Importante:</strong> este site usa os sistemas ABO e RhD como modelo educativo.
        Na medicina transfusional existem muitos outros antígenos e sistemas sanguíneos, então uma
        transfusão real nunca é decidida apenas por uma tabela da internet.
    </div>
</section>

<section class="card">
    <h2>1. O que realmente é um tipo sanguíneo?</h2>
    <p>
        O tipo sanguíneo é uma forma de identificar certas moléculas presentes na superfície das
        hemácias, os glóbulos vermelhos. Essas moléculas são chamadas de <strong>antígenos</strong>.
        O organismo também possui <strong>anticorpos</strong>, que ficam principalmente no plasma e
        ajudam o sistema imunológico a reconhecer estruturas que ele considera estranhas.
    </p>
    <p>
        Quando falamos que uma pessoa é A+, por exemplo, estamos juntando duas informações diferentes:
        ela pertence ao grupo <strong>A</strong> do sistema ABO e é <strong>RhD positiva</strong>.
        O "A" e o "+" não são a mesma coisa e vêm de sistemas diferentes.
    </p>
</section>

<section class="card">
    <h2>2. Antígenos e anticorpos: a parte mais importante</h2>

    <div class="grid">
        <div class="result-box">
            <h3>Antígenos</h3>
            <p>
                São estruturas que ficam na superfície das hemácias. Eles funcionam como uma espécie
                de identificação. No sistema ABO, os principais são os antígenos <strong>A</strong> e
                <strong>B</strong>.
            </p>
        </div>

        <div class="result-box">
            <h3>Anticorpos</h3>
            <p>
                São proteínas de defesa presentes no plasma. Elas podem reconhecer determinados
                antígenos como estranhos e participar de uma reação imunológica contra eles.
            </p>
        </div>
    </div>

    <p>
        É justamente a relação entre essas duas coisas que explica grande parte da compatibilidade.
        Se uma pessoa recebe hemácias que carregam um antígeno contra o qual seus anticorpos reagem,
        pode acontecer uma reação transfusional. Por isso, a compatibilidade é tratada com cuidado.
    </p>
</section>

<section class="card">
    <h2>3. Sistema ABO: o que muda entre A, B, AB e O?</h2>
    <p>
        No sistema ABO, o que muda principalmente é quais antígenos A e B aparecem nas hemácias e
        quais anticorpos ABO aparecem no plasma.
    </p>

    <div class="table-wrap">
        <table>
            <thead>
                <tr>
                    <th>Tipo</th>
                    <th>Antígenos nas hemácias</th>
                    <th>Anticorpos ABO no plasma</th>
                    <th>Em resumo</th>
                </tr>
            </thead>
            <tbody>
                <tr>
                    <td><strong>A</strong></td>
                    <td>A</td>
                    <td>Anti-B</td>
                    <td>Tem A, mas não B.</td>
                </tr>
                <tr>
                    <td><strong>B</strong></td>
                    <td>B</td>
                    <td>Anti-A</td>
                    <td>Tem B, mas não A.</td>
                </tr>
                <tr>
                    <td><strong>AB</strong></td>
                    <td>A e B</td>
                    <td>Não possui anti-A nem anti-B naturais</td>
                    <td>Tem os dois antígenos.</td>
                </tr>
                <tr>
                    <td><strong>O</strong></td>
                    <td>Nenhum A ou B</td>
                    <td>Anti-A e anti-B</td>
                    <td>Não tem A nem B nas hemácias.</td>
                </tr>
            </tbody>
        </table>
    </div>

    <p>
        Isso explica, por exemplo, por que o plasma de uma pessoa O contém anticorpos contra A e B,
        enquanto uma pessoa AB não possui esses dois anticorpos naturais no plasma. Para transfusão
        de hemácias, o que importa é principalmente não colocar no receptor um antígeno que cause
        uma reação com os anticorpos dele.
    </p>
</section>

<section class="card">
    <h2>4. Por que sangue incompatível pode causar problema?</h2>
    <p>
        Imagine que uma pessoa possui anticorpos que reconhecem o antígeno B como estranho. Se ela
        recebe muitas hemácias que carregam antígeno B, esses anticorpos podem se ligar a essas células
        e desencadear uma reação imunológica.
    </p>
    <p>
        Por isso, não basta perguntar "qual é o tipo do doador?". É preciso pensar nos antígenos que
        vêm nas hemácias do doador e naquilo que o organismo do receptor pode reconhecer como estranho.
        Além da tipagem ABO e RhD, os serviços de hemoterapia fazem outros testes antes de uma
        transfusão.
    </p>
</section>

<section class="card">
    <h2>5. E o fator Rh? O que significa o + e o -?</h2>
    <p>
        Neste site, o sinal <strong>+</strong> ou <strong>-</strong> representa principalmente o
        <strong>antígeno D do sistema Rh</strong>:
    </p>

    <div class="grid">
        <div class="result-box">
            <h3>Rh positivo (+)</h3>
            <p>
                A pessoa possui o antígeno D nas hemácias. Por isso, o tipo pode ser A+, B+, AB+ ou O+.
            </p>
        </div>
        <div class="result-box">
            <h3>Rh negativo (-)</h3>
            <p>
                A pessoa não possui o antígeno D nas hemácias. Por isso, o tipo pode ser A-, B-, AB- ou O-.
            </p>
        </div>
    </div>

    <p>
        Uma diferença importante em relação ao ABO é que uma pessoa Rh-negativa não nasce simplesmente
        com um "anti-D natural" da mesma forma que os anticorpos ABO aparecem. Anticorpos anti-D podem
        ser formados depois de uma exposição ao antígeno D, como pode acontecer em determinadas
        transfusões ou gestações. Esse processo é chamado de <strong>sensibilização</strong>.
    </p>

    <div class="alert warning-note">
        <strong>Na prática:</strong> para transfusão de hemácias, costuma-se evitar dar sangue Rh-positivo
        a uma pessoa Rh-negativa quando não há indicação específica para isso. Em uma situação real,
        a equipe de saúde considera o quadro clínico e os testes laboratoriais.
    </div>
</section>

<section class="card">
    <h2>6. Por que o O- é chamado de "doador universal"?</h2>
    <p>
        Essa expressão é uma simplificação usada principalmente para <strong>hemácias</strong>.
        As hemácias O- não apresentam os antígenos A, B e D principais usados neste modelo, então elas
        têm a maior compatibilidade básica entre os oito tipos mostrados no site.
    </p>
    <p>
        Já o AB+ costuma ser chamado de "receptor universal" de hemácias dentro desse mesmo modelo,
        porque possui A, B e D e, em termos ABO/RhD simplificados, pode receber de todos os oito tipos.
    </p>
    <p class="small-note">
        Essas expressões não significam que qualquer componente do sangue possa ser transfundido para
        qualquer pessoa. Plasma e plaquetas seguem outras regras, e uma transfusão real é feita com
        testes de compatibilidade.
    </p>
</section>

<section class="card">
    <h2>7. Genética: genótipo, fenótipo, dominância e codominância</h2>
    <p>
        Esta é a parte que explica por que duas pessoas com o mesmo tipo sanguíneo visível podem ter
        combinações genéticas diferentes. Para cada característica do sistema ABO, uma pessoa recebe
        <strong>um alelo da mãe e um alelo do pai</strong>. A combinação desses alelos forma o
        <strong>genótipo</strong>. O tipo que conseguimos observar no exame, como A, B, AB ou O, é o
        <strong>fenótipo</strong>.
    </p>

    <div class="genetics-flow">
        <div class="genetics-step"><strong>AA → tipo A</strong>Os dois alelos são A e o antígeno A é produzido.</div>
        <div class="genetics-step"><strong>AO → tipo A</strong>O A é dominante em relação ao O, então o fenótipo continua sendo A.</div>
        <div class="genetics-step"><strong>BB → tipo B</strong>Os dois alelos são B e o antígeno B é produzido.</div>
        <div class="genetics-step"><strong>BO → tipo B</strong>O B é dominante em relação ao O, então o fenótipo continua sendo B.</div>
        <div class="genetics-step"><strong>AB → tipo AB</strong>A e B são codominantes: os dois aparecem ao mesmo tempo.</div>
        <div class="genetics-step"><strong>OO → tipo O</strong>Não há A nem B para produzir os antígenos A ou B.</div>
    </div>

    <p>
        No sistema ABO, é importante não dizer simplesmente que "A é dominante e B é recessivo" ou que
        "um sempre vence o outro". O correto é: <strong>A e B são codominantes entre si</strong>. Quando uma
        pessoa recebe A de um dos pais e B do outro, o genótipo é AB e os dois antígenos aparecem nas
        hemácias. Já o alelo <strong>O é recessivo</strong> em relação tanto a A quanto a B. Por isso, AO
        resulta em tipo A e BO resulta em tipo B.
    </p>

    <div class="table-wrap">
        <table>
            <thead>
                <tr><th>Fenótipo</th><th>Genótipos possíveis</th><th>Como interpretar</th></tr>
            </thead>
            <tbody>
                <tr><td><strong>A</strong></td><td>AA ou AO</td><td>A aparece mesmo quando o outro alelo é O.</td></tr>
                <tr><td><strong>B</strong></td><td>BB ou BO</td><td>B aparece mesmo quando o outro alelo é O.</td></tr>
                <tr><td><strong>AB</strong></td><td>AB</td><td>A e B são codominantes e os dois aparecem.</td></tr>
                <tr><td><strong>O</strong></td><td>OO</td><td>É preciso receber O dos dois pais.</td></tr>
            </tbody>
        </table>
    </div>

    <h3>Por que isso muda a probabilidade do bebê?</h3>
    <p>
        Porque o exame normalmente mostra o fenótipo, e não revela sozinho qual das duas possibilidades
        genéticas está por trás dele. Uma pessoa tipo A pode ser AA ou AO, por exemplo. Se um casal for
        AO × BO, a primeira pessoa pode transmitir A ou O e a segunda pode transmitir B ou O. As quatro
        combinações básicas são AB, AO, BO e OO. Isso explica por que um casal A × B pode, em determinadas
        combinações, ter um filho O.
    </p>

    <h3>E o RhD?</h3>
    <p>
        O sinal + ou - depende principalmente da presença ou ausência do antígeno D. Para a simulação,
        este projeto usa um modelo simples em que <strong>D é dominante e d é recessivo</strong>: DD e Dd são
        tratados como Rh-positivos, enquanto dd é Rh-negativo. A biologia real do sistema Rh é mais
        complexa, então essa regra serve como simplificação didática do site.
    </p>

    <p>
        Como o tipo observado não revela sempre o genótipo exato, a calculadora reúne todas as combinações
        de genótipos compatíveis e produz uma única distribuição consolidada. Para isso, o projeto dá o
        mesmo peso a cada combinação completa de genótipos compatível. Isso é uma <strong>hipótese de
        modelagem</strong> criada para transformar a incerteza em uma única tabela; não é uma frequência
        populacional universal.
    </p>
</section>

<section class="card">
    <h2>8. Gestação: não é só Rh</h2>
    <p>
        Essa é uma das partes que mais causa confusão. O fator RhD é importante, mas ele não é a única
        possibilidade de incompatibilidade sanguínea durante a gestação.
    </p>

    <div class="grid">
        <div class="result-box">
            <h3>Incompatibilidade RhD</h3>
            <p>
                A situação clássica é uma gestante Rh-negativa com possibilidade de um feto Rh-positivo.
                Se houver sensibilização, anticorpos maternos anti-D podem atravessar a placenta e destruir
                hemácias fetais. A prevenção e o acompanhamento são feitos no pré-natal.
            </p>
        </div>

        <div class="result-box">
            <h3>Incompatibilidade ABO</h3>
            <p>
                Também pode acontecer. Um exemplo importante é quando a gestante pertence ao grupo O e
                o bebê é A, B ou, em algumas situações, AB. Esse mecanismo é diferente do RhD e pode
                contribuir para doença hemolítica do feto ou do recém-nascido.
            </p>
        </div>
    </div>

    <p>
        Além disso, existem anticorpos contra muitos outros antígenos das hemácias. Anticorpos de sistemas
        como Kell, Kidd, Duffy e outros podem ser relevantes em uma gestação. Por isso, uma avaliação real
        não olha somente para A/B/AB/O e positivo/negativo: a gestante pode fazer <strong>pesquisa de
        anticorpos</strong> durante o pré-natal.
    </p>

    <div class="alert info-note">
        <strong>Importante:</strong> dois tipos sanguíneos que parecem "incompatíveis" em uma tabela não
        significam que o casal não possa ter filhos. A questão é o risco imunológico específico e a forma
        como ele é acompanhado durante a gestação.
    </div>
</section>

