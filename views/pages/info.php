<section class="card">
    <h2>10. Existem tipos sanguíneos além dos oito?</h2>
    <p>
        Sim. Os oito tipos mostrados no site são uma combinação simplificada de ABO e RhD. A transfusão
        moderna considera muitos outros sistemas e antígenos. Na edição atual do banco da International Society
        of Blood Transfusion consultada em setembro de 2026, são registrados <strong>49 sistemas de grupos
        sanguíneos e 400 antígenos</strong>. Esses números podem mudar conforme novos sistemas e antígenos são
        reconhecidos.
    </p>

    <div class="grid">
        <div class="result-box">
            <h3>Fenótipo Bombay (Oh)</h3>
            <p>
                É uma condição extremamente rara em que falta o antígeno H, que normalmente serve de base
                para a formação dos antígenos A e B. A pessoa pode parecer grupo O em uma tipagem básica,
                mas não pode simplesmente receber sangue O comum. São necessários testes específicos e sangue
                compatível com esse fenótipo raro.
            </p>
        </div>

        <div class="result-box">
            <h3>Rh nulo (Rh-null)</h3>
            <p>
                É um fenótipo muito raro no qual faltam os antígenos do sistema Rh nas hemácias. O apelido
                "sangue dourado" ficou conhecido por causa da extrema raridade. Isso não significa que ele
                seja melhor; significa que encontrar sangue compatível pode ser muito difícil.
            </p>
        </div>
    </div>

    <p>
        Também existem fenótipos muito raros relacionados a outros sistemas, como Kell, Kidd, Duffy, MNS,
        Diego e vários outros. Alguns surgem pela ausência de antígenos que são muito comuns na população,
        e isso pode fazer com que o sangue compatível seja difícil de encontrar.
    </p>
</section>

<section class="card">
    <h2>11. Doação de sangue, plasma e plaquetas</h2>
    <p>
        Doar sangue é importante porque não existe um substituto completo para o sangue e os estoques
        precisam ser mantidos continuamente. O sangue doado pode ser separado em diferentes componentes,
        principalmente <strong>hemácias, plaquetas e plasma</strong>, que podem ser utilizados em situações
        diferentes.
    </p>

    <div class="grid three">
        <div class="result-box">
            <h3>Hemácias</h3>
            <p>São as células que transportam oxigênio. São a parte principal analisada pela compatibilidade deste site.</p>
        </div>
        <div class="result-box">
            <h3>Plaquetas</h3>
            <p>Participam da coagulação e ajudam a controlar sangramentos. A compatibilidade delas é mais complexa e não é calculada aqui.</p>
        </div>
        <div class="result-box">
            <h3>Plasma</h3>
            <p>É a parte líquida do sangue e carrega proteínas, sais e fatores de coagulação. As regras ABO do plasma não são iguais às das hemácias.</p>
        </div>
    </div>

    <div class="alert success">
        <strong>Por que isso importa?</strong> Uma única doação pode ser separada em componentes e ajudar mais
        de um paciente. O Ministério da Saúde informa que uma unidade pode beneficiar até quatro vidas,
        dependendo do processamento e do uso dos componentes.
    </div>
</section>

<section class="card">
    <h2>12. Curiosidades</h2>
    <div class="grid">
        <div class="result-box">
            <h3>O tipo sanguíneo não é só A, B, AB ou O</h3>
            <p>Esses quatro nomes resumem o sistema ABO. Existem muitos outros antígenos além deles.</p>
        </div>
        <div class="result-box">
            <h3>O positivo é muito importante para os estoques</h3>
            <p>Como é um tipo frequente, existe uma grande demanda por ele nos hemocentros brasileiros.</p>
        </div>
        <div class="result-box">
            <h3>O- é raro e muito útil em emergências</h3>
            <p>Ele é valorizado para uso emergencial de hemácias quando ainda não foi possível fazer a tipagem completa.</p>
        </div>
        <div class="result-box">
            <h3>Uma pessoa pode ter um sangue raro sem saber</h3>
            <p>O rótulo A+, por exemplo, não conta toda a história. Diferenças em outros antígenos só aparecem em testes mais específicos.</p>
        </div>
    </div>
</section>

<section class="card">
    <h2>13. Mitos e verdades</h2>

    <div class="grid">
        <div class="result-box good">
            <h3>Verdade: "ABO e Rh não são a história inteira."</h3>
            <p>Verdade. Existem muitos outros sistemas de grupos sanguíneos e antígenos.</p>
        </div>
        <div class="result-box good">
            <h3>Verdade: "Pais A e B podem ter filho O."</h3>
            <p>Sim. Isso é possível quando os dois carregam o alelo O, como no cruzamento AO × BO.</p>
        </div>
        <div class="result-box good">
            <h3>Verdade: "ABO também pode participar de incompatibilidade na gestação."</h3>
            <p>Sim. O caso clássico é a mãe do grupo O com feto A ou B, mas o resultado clínico varia.</p>
        </div>
        <div class="result-box bad">
            <h3>Mito: "Se os tipos sanguíneos dos pais forem diferentes, eles não podem ter filhos."</h3>
            <p>Falso. Diferença de tipo sanguíneo não impede uma gravidez.</p>
        </div>
        <div class="result-box bad">
            <h3>Mito: "O- é universal para qualquer coisa que venha do sangue."</h3>
            <p>Falso. A expressão "universal" é usada principalmente para hemácias no modelo ABO/RhD. Plasma e plaquetas têm regras diferentes.</p>
        </div>
        <div class="result-box bad">
            <h3>Mito: "O tipo sanguíneo define a personalidade da pessoa."</h3>
            <p>Não há base médica para usar o tipo sanguíneo como teste de personalidade.</p>
        </div>
        <div class="result-box bad">
            <h3>Mito: "Saber o tipo dos pais permite prever exatamente o sangue de um bebê."</h3>
            <p>Nem sempre. O fenótipo observado pode esconder mais de um genótipo, por isso existem probabilidades e incerteza.</p>
        </div>
        <div class="result-box bad">
            <h3>Mito: "Se alguém é Rh-negativo, a primeira gravidez sempre terá problema."</h3>
            <p>Falso. A incompatibilidade RhD é uma situação de risco que depende de fatores como exposição e presença de anticorpos, e existe prevenção.</p>
        </div>
    </div>
</section>

