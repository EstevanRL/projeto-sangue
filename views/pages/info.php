        A parte de cálculo foi criada como um modelo educativo. Ela representa a compatibilidade básica de
        hemácias pelos sistemas ABO/RhD e usa uma hipótese explícita para consolidar as probabilidades
        genéticas dos filhos. Na prática médica existem muitos outros antígenos, anticorpos, testes e
        situações especiais que não são reproduzidos pelo sistema.
    </p>
